#!/bin/bash
# 仅在数据卷首次初始化时执行：创建演示库与测试库及各自账户。
# 演示账户没有 DROP 权限，测试账户可以清空测试库。
set -euo pipefail

: "${DB_NAME:?}" "${DB_USER:?}" "${DB_PASSWORD:?}"
: "${TEST_DB_NAME:?}" "${TEST_DB_USER:?}" "${TEST_DB_PASSWORD:?}"

mysql -uroot -p"$MYSQL_ROOT_PASSWORD" <<SQL
CREATE DATABASE IF NOT EXISTS \`${DB_NAME}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
CREATE DATABASE IF NOT EXISTS \`${TEST_DB_NAME}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
CREATE USER IF NOT EXISTS '${DB_USER}'@'%' IDENTIFIED BY '${DB_PASSWORD}';
CREATE USER IF NOT EXISTS '${TEST_DB_USER}'@'%' IDENTIFIED BY '${TEST_DB_PASSWORD}';
GRANT SELECT, INSERT, UPDATE, DELETE, CREATE, ALTER, INDEX, REFERENCES ON \`${DB_NAME}\`.* TO '${DB_USER}'@'%';
GRANT SELECT, INSERT, UPDATE, DELETE, CREATE, ALTER, INDEX, REFERENCES, DROP ON \`${TEST_DB_NAME}\`.* TO '${TEST_DB_USER}'@'%';
SQL
